// Generate the edge functions' copy of the issuer ticker → domain map.
//
// The app's map lives in src/ (ISSUER_DOMAINS in src/lib/issuerLogo.ts, plus the
// auto-discovered DISCOVERED_DOMAINS in src/data/issuerDomains.ts), and a
// Supabase function can only import from its own directory or _shared — so the
// two maps are merged here instead of imported. Manual entries win, matching
// getIssuerLogoUrl's precedence.
//
// Run: node scripts/gen-edge-issuer-domains.mjs   (after `npm run fetch:logos`)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(resolve(root, p), "utf8");

// Pull the object literal out of each source and evaluate just that expression —
// importing the modules directly would drag in Vite-only syntax (import.meta.env).
function extractMap(src, marker) {
  const start = src.indexOf(marker);
  if (start < 0) throw new Error(`marker not found: ${marker}`);
  const open = src.indexOf("{", start);
  let depth = 0, end = open;
  for (; end < src.length; end++) {
    if (src[end] === "{") depth++;
    else if (src[end] === "}" && --depth === 0) break;
  }
  return new Function(`return ${src.slice(open, end + 1)}`)();
}

const manual = extractMap(read("src/lib/issuerLogo.ts"), "const ISSUER_DOMAINS");
const discovered = extractMap(read("src/data/issuerDomains.ts"), "DISCOVERED_DOMAINS");
const merged = { ...discovered, ...manual };

const entries = Object.entries(merged)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `  ${/^[A-Z][A-Z0-9]*$/.test(k) ? k : JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");

writeFileSync(
  resolve(root, "supabase/functions/_shared/issuerDomains.ts"),
  `// GENERATED by scripts/gen-edge-issuer-domains.mjs — do not edit by hand.\n` +
    `// Merge of ISSUER_DOMAINS (src/lib/issuerLogo.ts) and DISCOVERED_DOMAINS\n` +
    `// (src/data/issuerDomains.ts); manual entries win. Rerun after fetch:logos.\n\n` +
    `export const ISSUER_DOMAINS: Record<string, string> = {\n${entries}\n};\n`,
);
console.log(`wrote ${Object.keys(merged).length} domains`);
